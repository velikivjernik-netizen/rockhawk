@dataclass(frozen=True)
class SettingDef:
    key: str
    category: str
    category_label: str
    label: str
    description: str
    value_type: str
    default: Any
    risk: str
    editability: str
    restart_required: bool = False
    secret: bool = False
    enum_options: tuple[str, ...] | None = None
    floor: Any = None
    env_key: str | None = None
    env_mode: str = "pin"
    todo: bool = False
    tags: tuple[str, ...] = field(default_factory=tuple)

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "category": self.category,
            "category_label": self.category_label,
            "label": self.label,
            "description": self.description,
            "value_type": self.value_type,
            "default": None if self.secret else self.default,
            "risk": self.risk,
            "editability": self.editability,
            "restart_required": self.restart_required,
            "secret": self.secret,
            "enum_options": list(self.enum_options) if self.enum_options else None,
            "floor": self.floor,
            "env_key": self.env_key,
            "env_mode": self.env_mode,
            "todo": self.todo,
            "tags": list(self.tags),
        }


def _s(**kwargs: Any) -> SettingDef:
    return SettingDef(**kwargs)


