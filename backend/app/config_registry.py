REGISTRY: dict[str, SettingDef] = {item.key: item for item in SETTINGS}

CATEGORIES: list[dict[str, str]] = []
_seen: set[str] = set()
for item in SETTINGS:
    if item.category not in _seen:
        _seen.add(item.category)
        CATEGORIES.append({"id": item.category, "label": item.category_label})
CATEGORIES.append({"id": "history", "label": "18. Config revision history, import/export, approval, rollback"})


def get_definition(key: str) -> SettingDef:
    if key not in REGISTRY:
        raise KeyError(key)
    return REGISTRY[key]
